"""Corpus statistics + manifest (sha256 of every output) -> data/corpus/MANIFEST.json
and docs/corpus_stats.md. Re-run after every build; commit the stats file."""
from __future__ import annotations

import hashlib
import json
from collections import Counter
from pathlib import Path

from .common import CORPUS, ROOT, read_jsonl
from .schemas import SCHEMA_VERSION


def sha(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def build() -> dict:
    files = sorted(p for p in CORPUS.rglob("*") if p.is_file() and p.suffix in {".jsonl", ".json"}
                   and p.name != "MANIFEST.json")
    manifest = {"schema_version": SCHEMA_VERSION,
                "files": {str(p.relative_to(CORPUS)).replace("\\", "/"):
                          {"sha256": sha(p), "bytes": p.stat().st_size,
                           "rows": sum(1 for _ in p.open(encoding="utf-8")) if p.suffix == ".jsonl" else None}
                          for p in files}}
    (CORPUS / "MANIFEST.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")

    S = {}
    ch = list(read_jsonl(CORPUS / "c1_world" / "chunks.jsonl"))
    S["c1"] = {"documents": sum(1 for _ in read_jsonl(CORPUS / "c1_world" / "documents.jsonl")),
               "chunks": len(ch), "tokens": sum(c["n_tokens"] for c in ch),
               "entity_types": Counter(c["entity_type"] for c in ch).most_common(),
               "scopes": Counter(s.split(":")[0] for c in ch for s in c["scopes"]).most_common(),
               "spoiler_chunks": sum(bool(c.get("spoiler")) for c in ch),
               "restricted_chunks": sum(bool(c.get("restricted_by")) for c in ch),
               "relations": sum(1 for _ in read_jsonl(CORPUS / "c1_world" / "relations.jsonl"))}
    npcs = list(read_jsonl(CORPUS / "c2_profiles" / "npcs.jsonl"))
    S["c2"] = {"npcs": len(npcs), "review_status": Counter(p["review_status"] for p in npcs).most_common(),
               "dialogue_lines": sum(len(p.get("dialogue_samples", [])) for p in npcs),
               "knowledge_items": Counter(k["visibility"] for p in npcs for k in p.get("knowledge", [])).most_common()}
    qs = list(read_jsonl(CORPUS / "c3_quests" / "quests.jsonl"))
    S["c3"] = {"quests": len(qs), "stages": sum(len(q.get("stages", [])) for q in qs),
               "in_scope": sum("whiterun" in q.get("scope_tags", []) for q in qs),
               "world_effects": sum(len(q.get("world_effects", [])) for q in qs)}
    c4 = CORPUS / "c4_dialogue"
    if (c4 / "scenarios.jsonl").exists():
        sc = list(read_jsonl(c4 / "scenarios.jsonl"))
        S["c4_scenarios"] = {"n": len(sc), "split": Counter(s["split"] for s in sc).most_common(),
                             "behavior": Counter(s["behavior"] for s in sc).most_common(),
                             "avg_prompt_tokens": round(sum(len(s["system_prompt"]) for s in sc) / 4 / max(1, len(sc)))}
    if (c4 / "seed_uesp_dialogue.jsonl").exists():
        sd = list(read_jsonl(c4 / "seed_uesp_dialogue.jsonl"))
        S["c4_seed"] = {"n": len(sd), "flagged": sum(bool(e["quality"]["flags"]) for e in sd)}
    gen = c4 / "generated"
    if gen.exists():
        S["c4_generated"] = {p.stem: sum(1 for _ in p.open(encoding="utf-8")) for p in gen.glob("*.jsonl")}
    if (CORPUS / "eval" / "eval_cases.jsonl").exists():
        ev = list(read_jsonl(CORPUS / "eval" / "eval_cases.jsonl"))
        S["eval"] = {"n": len(ev), "by_dimension": Counter(e["dimension"] for e in ev).most_common()}

    md = ["# Corpus statistics (auto-generated by `python -m skyrimllm_data.report`)", "",
          f"Schema version: {SCHEMA_VERSION}", ""]
    for k, v in S.items():
        md += [f"## {k}", "", "```json", json.dumps(v, indent=1, ensure_ascii=False), "```", ""]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "corpus_stats.md").write_text("\n".join(md), encoding="utf-8")
    return {k: {kk: vv for kk, vv in v.items() if not isinstance(vv, list)} for k, v in S.items()}


if __name__ == "__main__":
    print(json.dumps(build(), indent=1))
